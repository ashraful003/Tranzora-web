/** Document expiry status from its expiry date (30-day warning window). */
export function docStatus(expiry: unknown, today = new Date()): string {
  if (!expiry || typeof expiry !== "string") return "No Expiry";
  const days = Math.floor((Date.parse(expiry) - today.getTime()) / 86400000);
  if (days < 0) return "Expired";
  if (days <= 30) return "Expiring Soon";
  return "Valid";
}
